"""Create the public static-site artifact from an explicit allowlist."""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "exports" / "site-release"
MARKER = ROOT / "exports" / ".site-release-generated"
MARKER_TEXT = "Generated by tools/package_site.py; safe to replace with make package-site.\n"
DIST = ROOT / "dist"
MANIFEST = DIST / "manifest.json"


def _built_site_files() -> list[Path]:
    if not MANIFEST.is_file():
        raise FileNotFoundError("Vite build not found; run `npm run build` before packaging the site")
    manifest: dict[str, Any] = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if "index.html" not in manifest:
        raise ValueError("Vite manifest has no index.html entry")

    files: set[Path] = {Path("index.html")}
    if not (DIST / "index.html").is_file():
        raise FileNotFoundError("Vite build has no dist/index.html entry")
    pending = ["index.html"]
    visited: set[str] = set()
    while pending:
        key = pending.pop()
        if key in visited:
            continue
        visited.add(key)
        entry = manifest.get(key)
        if not isinstance(entry, dict):
            raise ValueError(f"Vite manifest entry is missing or invalid: {key}")
        for item in [entry.get("file"), *entry.get("css", []), *entry.get("assets", [])]:
            if not item:
                continue
            relative = Path(item)
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"Refusing unsafe Vite asset path: {item}")
            if not (DIST / relative).is_file():
                raise FileNotFoundError(f"Built public asset is missing: {item}")
            files.add(relative)
        pending.extend(entry.get("imports", []))
        pending.extend(entry.get("dynamicImports", []))

    return sorted(files)


def package_site() -> Path:
    exports = ROOT / "exports"
    exports.mkdir(parents=True, exist_ok=True)
    built_files = _built_site_files()
    static_files = [
        (ROOT / "NOTICE.md", Path("NOTICE.md")),
        (ROOT / "data/canonical/legacy_aliases.json", Path("data/canonical/legacy_aliases.json")),
    ]
    for source, _ in static_files:
        if not source.is_file():
            raise FileNotFoundError(f"Public site input is missing: {source.relative_to(ROOT)}")
    if OUTPUT.is_symlink():
        raise ValueError(f"Refusing to replace symlinked output directory: {OUTPUT}")
    if OUTPUT.exists():
        if not MARKER.is_file() or MARKER.read_text(encoding="utf-8") != MARKER_TEXT:
            raise ValueError(
                f"Refusing to replace {OUTPUT}: it is not marked as generated by this tool"
            )
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir(parents=True)
    for relative in built_files:
        source = DIST / relative
        destination = OUTPUT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    for source, relative in static_files:
        destination = OUTPUT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    MARKER.write_text(MARKER_TEXT, encoding="utf-8")
    return OUTPUT


if __name__ == "__main__":
    print(package_site())
